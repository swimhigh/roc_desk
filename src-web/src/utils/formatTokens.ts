/** AI 对话消耗的 token 数展示——数量级大的时候直接看一串 5/6 位数字很难一眼
 * 判断到底是"几千"还是"几万"（2026-09 用户反馈）。10000 以下保留原始整数
 * （几百/几千直接看数字更直观，非要写成"0.08万"反而更难读）；10000 及以上
 * 换算成"万"、保留两位小数——token 消耗本来就是"大概花了多少"的量级概念，
 * 不需要精确到个位。 */
export function formatTokenCount(n: number): string {
  if (n < 10000) return String(n);
  return `${(n / 10000).toFixed(2)}万`;
}
